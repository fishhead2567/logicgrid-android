package dev.logicgrid.core

import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.DynamicTest
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.TestFactory
import java.io.File

/**
 * Replays recorded Python board sessions through the Kotlin [Board].
 *
 * Hand-porting the reference test suite would test my re-reading of those
 * tests, not the faithfulness of the port. These fixtures instead record the
 * exact state after every step of a deterministic walk over real puzzles, so a
 * divergence in forced elimination, in assist, or in conflict detection is
 * caught at the step it first appears, in the shape it first appears.
 *
 * Generated by `scripts/board_fixtures.py` in the generator repo. A cell is
 * encoded as `min*R + max` over indices into [Schema.allRefs], which the
 * Kotlin side rebuilds from the puzzle JSON -- so there is no ordering to keep
 * in sync by hand.
 */
class BoardConformanceTest {

    private data class Fixture(val name: String, val root: JsonObject)

    private fun fixtures(): List<Fixture> {
        val dir = File("src/test/resources/fixtures")
        assertTrue(dir.isDirectory, "fixtures missing at ${dir.absolutePath}")
        return dir.listFiles { f -> f.name.endsWith(".board.json") }!!
            .sortedBy { it.name }
            .map { Fixture(it.name, PuzzleJson.json.parseToJsonElement(it.readText()).jsonObject) }
    }

    /** Puzzle rebuilt from the fixture's own copy, so it cannot drift. */
    private fun puzzleOf(root: JsonObject): Puzzle =
        PuzzleJson.fromObject(root.getValue("puzzle").jsonObject)

    private fun encode(closure: Closure, index: Map<Ref, Int>, size: Int): Pair<List<Int>, List<Int>> {
        val yes = mutableListOf<Int>()
        val no = mutableListOf<Int>()
        for ((cell, value) in closure.marks) {
            val i = index.getValue(cell.a)
            val j = index.getValue(cell.b)
            val code = minOf(i, j) * size + maxOf(i, j)
            if (value) yes += code else no += code
        }
        return yes.sorted() to no.sorted()
    }

    @TestFactory
    fun `kotlin board matches the reference implementation step for step`(): List<DynamicTest> =
        fixtures().flatMap { fixture ->
            val puzzle = puzzleOf(fixture.root)
            val refs = fixture.root.getValue("refs").jsonArray.map {
                Ref.parse(it.jsonPrimitive.content)
            }
            // The ref order must be derivable from the puzzle alone; if it is
            // not, every cell code below is meaningless.
            assertEquals(
                refs, puzzle.schema.allRefs,
                "${fixture.name}: ref order diverges from the puzzle schema",
            )
            val index = puzzle.schema.refIndex
            val size = refs.size

            fixture.root.getValue("traces").jsonArray.map { traceElement ->
                val trace = traceElement.jsonObject
                val assist = trace.getValue("assist").jsonPrimitive.content.toBoolean()
                DynamicTest.dynamicTest("${fixture.name} assist=$assist") {
                    var state = BoardState(assist = assist)
                    var closure = Closure(emptyMap())

                    for (stepElement in trace.getValue("steps").jsonArray) {
                        val step = stepElement.jsonObject
                        val n = step.getValue("step").jsonPrimitive.int
                        val a = refs[step.getValue("a").jsonPrimitive.int]
                        val b = refs[step.getValue("b").jsonPrimitive.int]
                        val action = step.getValue("action").jsonPrimitive.content
                        val expectConflict =
                            step.getValue("conflict").jsonPrimitive.content.toBoolean()

                        val result: MarkResult? = when (action) {
                            "yes" -> Board.setMark(puzzle, state, a, b, true)
                            "no" -> Board.setMark(puzzle, state, a, b, false)
                            "clear" -> Board.clearMark(puzzle, state, a, b)
                            "clear_noop" -> null
                            else -> error("unknown action '$action'")
                        }

                        val where = "${fixture.name} assist=$assist step $n ($action)"
                        when (result) {
                            null -> assertTrue(
                                action == "clear_noop" || action == "clear",
                                "$where: unexpected no-op",
                            )
                            is MarkResult.Ok -> {
                                assertTrue(!expectConflict, "$where: expected a conflict")
                                state = result.state
                                closure = result.closure
                            }
                            is MarkResult.Rejected -> assertTrue(
                                expectConflict,
                                "$where: unexpected conflict ${result.reason}",
                            )
                        }

                        val (yes, no) = encode(closure, index, size)
                        val expected = step.getValue("closure").jsonObject
                        assertEquals(
                            expected.getValue("yes").jsonArray.map { it.jsonPrimitive.int },
                            yes, "$where: YES cells differ",
                        )
                        assertEquals(
                            expected.getValue("no").jsonArray.map { it.jsonPrimitive.int },
                            no, "$where: NO cells differ",
                        )
                        assertEquals(
                            step.getValue("mistakes").jsonPrimitive.int,
                            Board.mistakes(puzzle, closure).size,
                            "$where: mistake count differs",
                        )
                        val answer = Board.answer(puzzle, closure)
                        assertEquals(
                            step.getValue("answerComplete").jsonPrimitive.content.toBoolean(),
                            Board.answerComplete(answer),
                            "$where: answerComplete differs",
                        )
                        assertEquals(
                            step.getValue("solved").jsonPrimitive.content.toBoolean(),
                            Board.solved(puzzle, closure),
                            "$where: solved differs",
                        )
                    }
                }
            }
        }

    /**
     * The closure must not depend on the order marks were inserted.
     *
     * The fixtures replay one fixed order, so an order-dependence bug would be
     * invisible to them -- and it is the likeliest Kotlin-specific bug, since
     * the reference iterates insertion-ordered dicts and a `HashMap` here would
     * not. The fixpoint is monotone and a cell is never overwritten, so the
     * result is order-independent by construction; this asserts it.
     */
    @Test
    fun `closure is independent of mark insertion order`() {
        val random = java.util.Random(20261118)
        for (fixture in fixtures()) {
            val puzzle = puzzleOf(fixture.root)
            for (assist in listOf(false, true)) {
                // Build a non-trivial legal state.
                var state = BoardState(assist = assist)
                val refs = puzzle.schema.allRefs
                var placed = 0
                var guard = 0
                while (placed < 6 && guard++ < 400) {
                    val a = refs[random.nextInt(refs.size)]
                    val b = refs[random.nextInt(refs.size)]
                    if (a.cat == b.cat) continue
                    val value = random.nextBoolean()
                    val r = Board.setMark(puzzle, state, a, b, value)
                    if (r is MarkResult.Ok) { state = r.state; placed++ }
                }
                val baseline = (Board.closure(puzzle, state) as ClosureResult.Ok).closure

                repeat(5) {
                    val shuffled = state.userMarks.entries.shuffled(random.let {
                        kotlin.random.Random(random.nextLong())
                    }).associate { it.key to it.value }
                    val other = Board.closure(puzzle, state.copy(userMarks = shuffled))
                    other as ClosureResult.Ok
                    assertEquals(
                        baseline.marks, other.closure.marks,
                        "${fixture.name} assist=$assist: closure changed with insertion order",
                    )
                }
            }
        }
    }
}
